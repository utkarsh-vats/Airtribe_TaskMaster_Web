// Generate src/lib/api/schema.d.ts from the backend's OpenAPI spec.
//
//   npm run api:types
//
// The spec URL comes from API_SPEC_URL in the environment, then .env.local, then the default
// below. Start the backend first (`npm run dev` in Airtribe_TaskMaster).

import { existsSync, readFileSync } from 'node:fs';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseEnv } from 'node:util';

import openapiTS, { astToString, COMMENT_HEADER } from 'openapi-typescript';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outFile = path.join(root, 'src', 'lib', 'api', 'schema.d.ts');
const DEFAULT_SPEC_URL = 'http://localhost:3000/openapi.json';
const HEADER = '// Generated by npm run api:types — do not edit.\n';

/** A failure with a message for the person running the script (printed without a stack). */
class ScriptError extends Error {}

function resolveSpecUrl() {
    if (process.env.API_SPEC_URL) return process.env.API_SPEC_URL;
    const envFile = path.join(root, '.env.local');
    if (existsSync(envFile)) {
        const fromFile = parseEnv(readFileSync(envFile, 'utf8')).API_SPEC_URL;
        if (fromFile) return fromFile;
    }
    return DEFAULT_SPEC_URL;
}

async function fetchSpec(url) {
    let response;
    try {
        response = await fetch(url, {
            headers: { accept: 'application/json' },
            signal: AbortSignal.timeout(10_000),
        });
    } catch (error) {
        const reason = error instanceof Error ? (error.cause?.code ?? error.message) : error;
        throw new ScriptError(
            `couldn't reach the API at ${url} (${reason}).\n` +
                '  Start the backend (npm run dev in Airtribe_TaskMaster) or set API_SPEC_URL.',
        );
    }

    // Read the body in full either way, so no open stream is left behind at exit.
    const body = await response.text();
    if (!response.ok) {
        throw new ScriptError(
            `${url} responded ${response.status} ${response.statusText}; expected the OpenAPI JSON.`,
        );
    }

    let spec;
    try {
        spec = JSON.parse(body);
    } catch {
        throw new ScriptError(`${url} didn't return JSON.`);
    }
    if (typeof spec?.openapi !== 'string') {
        throw new ScriptError(`${url} returned JSON without an "openapi" field — not a spec.`);
    }
    return spec;
}

async function main() {
    const specUrl = resolveSpecUrl();
    console.log(`api:types — fetching ${specUrl}`);
    const spec = await fetchSpec(specUrl);

    const ast = await openapiTS(spec);
    const source = HEADER + COMMENT_HEADER + astToString(ast);

    await mkdir(path.dirname(outFile), { recursive: true });
    await writeFile(outFile, source.replace(/\r\n/g, '\n'), 'utf8');

    const pathCount = Object.keys(spec.paths ?? {}).length;
    const schemaCount = Object.keys(spec.components?.schemas ?? {}).length;
    console.log(
        `api:types — wrote ${path.relative(root, outFile)} (OpenAPI ${spec.openapi}, ` +
            `${spec.info?.title ?? 'untitled'} ${spec.info?.version ?? ''}: ` +
            `${pathCount} paths, ${schemaCount} schemas)`,
    );
}

try {
    await main();
} catch (error) {
    if (!(error instanceof ScriptError)) throw error;
    console.error(`\n✖ api:types — ${error.message}\n`);
    // exitCode, not process.exit(): let open handles close (Node on Windows asserts otherwise).
    process.exitCode = 1;
}
